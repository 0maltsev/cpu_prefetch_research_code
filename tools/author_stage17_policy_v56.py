"""Render D-204 preflight30 first, then operational56; no execution authority."""
from __future__ import annotations

import argparse
import json
import pathlib
import sys

import author_stage17_policy_v55 as predecessor
import stage17_semantic_verifier_v56 as verifier
import stage17_read_only_preflight_semantic_verifier_v30 as preflight

_BASE = predecessor._BASE
ROOTS = (*predecessor.ROOTS,
    "stage17_operational_cli_v16", "stage17_phase_controller_v23",
    "stage17_q15_session_controller_v18", "stage17_state_journal_v50",
    "stage17_semantic_verifier_v56", "stage17_read_only_preflight_executor_v30",
    "stage17_read_only_preflight_semantic_verifier_v30",
    "stage17_pilot_candidate_artifact_v10", "stage17_operational_semantics_v14")
SUCCESSOR_BINDINGS = (
    preflight.POLICY_PATH, preflight.POLICY_SCHEMA_PATH, preflight.ADR_0204_PATH,
    verifier.POLICY_SCHEMA.as_posix(), predecessor.verifier.POLICY_PATH.as_posix(),
    "tools/author_stage17_policy_v56.py", "tools/check_stage17_preflight_successor.py",
    "config/schemas/stage17-pilot-candidate-external-contract-v8.schema.json",
    "config/schemas/stage17-runtime-release-provenance-v8.schema.json",
    "tests/test_stage17_discovery_metadata.py")


def render_preflight(root):
    root = root.resolve()
    policy = json.loads((root / preflight.POLICY_V29_PATH).read_bytes())
    policy.update(schema_version="cpu-prefetch-stage17-read-only-preflight-evidence-admission-policy/30",
        policy_id="STAGE17-READ-ONLY-PREFLIGHT-EVIDENCE-ADMISSION-POLICY-v30",
        policy_version="30")
    previous = policy["predecessor"]
    policy["predecessor"] = {key: value for key, value in previous.items()
                            if key not in {"policy_v28", "adr_0168"}}
    policy["predecessor"].update(
        policy_v29=_BASE.binding(root, preflight.POLICY_V29_PATH),
        adr_0204=_BASE.binding(root, preflight.ADR_0204_PATH))
    policy["implementations"] = {key: _BASE.binding(root, path)
                                for key, path in preflight.IMPLEMENTATION_PATHS.items()}
    policy["operational_implementations"] = {
        key: _BASE.binding(root, binding["path"])
        for key, binding in policy["operational_implementations"].items()}
    return policy


def render(root):
    root = root.resolve()
    policy = predecessor.render(root)
    policy.update(schema_version="cpu-prefetch-stage17-operational-evidence-admission-policy/56",
        policy_id="STAGE17-OPERATIONAL-EVIDENCE-ADMISSION-POLICY-v56", policy_version="56",
        predecessor=_BASE.binding(root, predecessor.verifier.POLICY_PATH.as_posix()),
        predecessor_status="SUPERSEDED_REBINDS_D204_PREFLIGHT_EXECUTION",
        runtime_import_roots=list(ROOTS),
        runtime_closure={pathlib.PurePosixPath(path).stem: _BASE.binding(root, path)
            for path in sorted(verifier.discover_python_closure(root, ROOTS))},
        entries=[dict(input_id=key, status="IMPLEMENTED", verifier_id=verifier.VERIFIER_ID,
                      verifier_version=verifier.VERIFIER_VERSION) for key in verifier.INPUT_IDS])
    for path in SUCCESSOR_BINDINGS:
        policy["bindings"][path.replace("/", "__").replace(".", "_")] = _BASE.binding(root, path)
    return policy


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=pathlib.Path, default=pathlib.Path(__file__).resolve().parents[1])
    parser.add_argument("--preflight", action="store_true")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    path = preflight.POLICY_PATH if args.preflight else verifier.POLICY_PATH
    payload = _BASE.canonical((render_preflight if args.preflight else render)(args.root))
    if args.check:
        if not (args.root / path).is_file() or (args.root / path).read_bytes() != payload:
            print("stage17-policy-v56: FAIL generated bytes differ: " + str(path), file=sys.stderr)
            return 1
        print("stage17-policy-v56: PASS " + str(path))
        return 0
    sys.stdout.buffer.write(payload)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
