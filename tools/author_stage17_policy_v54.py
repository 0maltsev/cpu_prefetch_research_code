"""Render the prospective, source-bound calibration policy v54."""

from __future__ import annotations

import argparse
import pathlib
import sys

import author_stage17_policy_v53 as predecessor
import stage17_semantic_verifier_v54 as verifier

ROOTS = tuple(predecessor.ROOTS) + (
    "stage17_operational_semantics_v12", "stage17_output_registry_v8",
    "stage17_phase_controller_v21", "stage17_operational_cli_v14",
    "stage17_state_journal_v48", "stage17_semantic_verifier_v54",
)
SUCCESSOR_BINDINGS = (
    "docs/decisions/0177-stage17-calibration-mapping-and-capability.md",
    "config/stage17/stage17-operational-evidence-admission-policy-v53.json",
    "config/schemas/stage17-operational-evidence-admission-policy-v54.schema.json",
    "config/stage17/stage17-fixed-phase-actions-v6.json",
    "config/schemas/stage17-fixed-phase-actions-v6.schema.json",
    "config/schemas/stage17-calibration-hardware-state-v2.schema.json",
    "src/runner/stage17_fixed_action.cpp", "src/runner/runner.cpp",
    "src/platform/q15_msr.cpp", "include/cpu_prefetch/platform/q15_msr.hpp",
    "include/cpu_prefetch/runner/runner.hpp",
    "include/cpu_prefetch/runner/software_prefetch.hpp",
    "tools/stage17_output_registry_v8.py", "tools/stage17_phase_controller_v21.py",
    "tools/stage17_operational_cli_v14.py", "tools/stage17_state_journal_v48.py",
    "tools/stage17_operational_semantics_v12.py", "tools/stage17_semantic_verifier_v54.py",
)


def render(root: pathlib.Path) -> dict[str, object]:
    policy = predecessor.render(root)
    policy.update({
        "schema_version": "cpu-prefetch-stage17-operational-evidence-admission-policy/54",
        "policy_id": "STAGE17-OPERATIONAL-EVIDENCE-ADMISSION-POLICY-v54",
        "policy_version": "54",
        "predecessor": predecessor._BASE.binding(root, predecessor.verifier.POLICY_PATH.as_posix()),
        "predecessor_status": "SUPERSEDED_ADDS_D177_CALIBRATION_MAPPING_AND_CAPABILITY",
        "runtime_import_roots": list(ROOTS),
        "runtime_closure": {
            pathlib.PurePosixPath(path).stem: predecessor._BASE.binding(root, path)
            for path in sorted(verifier.discover_python_closure(root, ROOTS))
        },
        "entries": [
            {"input_id": input_id, "status": "IMPLEMENTED",
             "verifier_id": verifier.VERIFIER_ID, "verifier_version": verifier.VERIFIER_VERSION}
            for input_id in verifier.INPUT_IDS
        ],
    })
    bindings = dict(policy["bindings"])
    for path in SUCCESSOR_BINDINGS:
        bindings[path.replace("/", "__").replace(".", "_")] = predecessor._BASE.binding(root, path)
    policy["bindings"] = bindings
    return policy


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--root", type=pathlib.Path, default=pathlib.Path(__file__).parents[1])
    parser.add_argument("--check", action="store_true")
    arguments = parser.parse_args()
    root = arguments.root.resolve()
    payload = predecessor._BASE.canonical(render(root))
    if arguments.check:
        destination = root / verifier.POLICY_PATH
        if not destination.is_file() or destination.read_bytes() != payload:
            print("stage17-policy-v54: FAIL: generated bytes differ", file=sys.stderr)
            return 1
        print("stage17-policy-v54: PASS")
        return 0
    sys.stdout.buffer.write(payload)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
