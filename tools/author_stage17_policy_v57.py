def render_preflight(root):
    root = root.resolve()
    policy = json.loads((root / preflight.POLICY_V30_PATH).read_bytes())
    policy.update(schema_version="cpu-prefetch-stage17-read-only-preflight-evidence-admission-policy/31",
        policy_id="STAGE17-READ-ONLY-PREFLIGHT-EVIDENCE-ADMISSION-POLICY-v31",
        policy_version="31")
    previous = policy["predecessor"]
    policy["predecessor"] = {key: value for key, value in previous.items()
                            if key not in {"policy_v29", "adr_0204"}}
    policy["predecessor"].update(
        policy_v30=_BASE.binding(root, preflight.POLICY_V30_PATH),
        adr_0208=_BASE.binding(root, preflight.ADR_0208_PATH))
    policy["implementations"] = {key: _BASE.binding(root, path)
                                for key, path in preflight.IMPLEMENTATION_PATHS.items()}
    policy["operational_implementations"] = {
        key: _BASE.binding(root, binding["path"])
        for key, binding in policy["operational_implementations"].items()}
    return policy


def render(root):
    root = root.resolve()
    policy = predecessor.render(root)
    policy.update(schema_version="cpu-prefetch-stage17-operational-evidence-admission-policy/57",
        policy_id="STAGE17-OPERATIONAL-EVIDENCE-ADMISSION-POLICY-v57", policy_version="57",
        predecessor=_BASE.binding(root, predecessor.verifier.POLICY_PATH.as_posix()),
        predecessor_status="SUPERSEDED_REBINDS_D208_DISCOVERY_V2",
        runtime_import_roots=list(ROOTS),
        runtime_closure={pathlib.PurePosixPath(path).stem: _BASE.binding(root, path)
            for path in sorted(verifier.discover_python_closure(root, ROOTS))},
        entries=[dict(input_id=key, status="IMPLEMENTED", verifier_id=verifier.VERIFIER_ID,
                      verifier_version=verifier.VERIFIER_VERSION) for key in verifier.INPUT_IDS])
    for path in SUCCESSOR_BINDINGS:
        policy["bindings"][path.replace("/", "__").replace(".", "_")] = _BASE.binding(root, path)
    return policy


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=pathlib.Path, default=pathlib.Path(__file__).resolve().parents[1])
    parser.add_argument("--preflight", action="store_true")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    path = preflight.POLICY_PATH if args.preflight else verifier.POLICY_PATH
    payload = _BASE.canonical((render_preflight if args.preflight else render)(args.root))
    if args.check:
        if not (args.root / path).is_file() or (args.root / path).read_bytes() != payload:
            print("stage17-policy-v57: FAIL generated bytes differ: " + str(path), file=sys.stderr)
            return 1
        print("stage17-policy-v57: PASS " + str(path))
        return 0
    sys.stdout.buffer.write(payload)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
