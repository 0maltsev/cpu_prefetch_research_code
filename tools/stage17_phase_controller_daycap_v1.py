def _clone_module(module, replacements):
    scope = dict(vars(module))
    clones = {}
    for name, value in vars(module).items():
        if isinstance(value, types.FunctionType) and value.__module__ == module.__name__:
            if value not in clones:
                clones[value] = metadata._clone(value, scope)
            scope[name] = clones[value]
    scope.update(replacements)
    return types.SimpleNamespace(**scope)


def _uuid(value):
    admission.require(type(value) is str and re.fullmatch(
        r'[0-9a-f]{8}(?:-[0-9a-f]{4}){3}-[0-9a-f]{12}', value), 'verified boot UUID required')


def _read_historical(raw, root):
    document = admission._json(raw)
    admission.fields(document, 'schema_version historical_context original_plan compatibility boot_id '
                     'execution_authority phase18_authority', 'historical configuration')
    admission.same(document['schema_version'], SCHEMA, 'historical configuration schema')
    _uuid(document['boot_id'])
    for flag in ('execution_authority', 'phase18_authority'):
        admission.same(document[flag], False, 'historical configuration authority')
    reader = admission.BoundReader()
    for key in ('historical_context', 'compatibility'):
        admission.require(Path(document[key]['path']).parent == root, 'historical packet namespace: ' + key)
    context = reader.document(document['historical_context'])
    admission.fields(context, 'schema_version boot_id resolutions execution_authority phase18_authority',
                     'historical context export')
    admission.same(context['schema_version'], CONTEXT_SCHEMA, 'historical context export schema')
    _uuid(context['boot_id'])
    admission.same(context['boot_id'], document['boot_id'], 'same historical/current verified boot')
    for flag in ('execution_authority', 'phase18_authority'):
        admission.same(context[flag], False, 'historical context authority')
    admission.fields(context['resolutions'], 'S17-EXT-004 S17-EXT-006', 'historical context resolutions')
    resolutions = {}
    for key, row in context['resolutions'].items():
        admission.fields(row, 'semantic_context', 'historical resolution')
        admission.require(type(row['semantic_context']) is dict, 'actual old semantic context required')
        resolutions[key] = types.SimpleNamespace(semantic_context=row['semantic_context'])
    validation = types.SimpleNamespace(resolutions=resolutions)
    old = resolutions['S17-EXT-006'].semantic_context
    admission.same(old['source_revision'], handoff.original.SOURCE, 'actual historical source42')
    admission.same(old['release_artifact_sha256'], handoff.OLD_WORKER, 'actual historical worker7ab')
    admission.same(old['inventory_sha256'], handoff.original.INVENTORY, 'actual historical inventory')
    plan = reader.document(document['original_plan'])
    admission.same(plan['source_revision'], old['source_revision'], 'actual old plan source')
    for key in resolutions:
        admission.same(plan['stand_id'], resolutions[key].semantic_context['stand_id'], 'actual old plan stand')
    proof = reader.document(document['compatibility'])
    admission.same(proof['schema_version'], handoff.SCHEMA, 'bound compatibility schema')
    admission.same(proof['original_plan'], document['original_plan'], 'actual historical plan binding')
    admission.same(proof['scope'], dict(decision='D254', purpose=handoff.PURPOSE,
        stand_id=plan['stand_id'], boot_id=document['boot_id']), 'bound compatibility scope')
    for flag in ('execution_authority', 'phase18_authority'):
        admission.same(proof[flag], False, 'compatibility authority')
    reader.finish()
    return document, context, validation, plan, proof


def configure_historical_inputs(document, packet_root):
    """Pin authenticated data only; identical reentry is allowed, replacement is not."""
    global _HISTORICAL
    try:
        root = Path(str(admission.contract._path(str(packet_root))))
        admission.require(root.is_dir() and root.resolve(strict=True) == root, 'canonical packet root required')
        admission.require(type(document) is dict, 'historical configuration must be JSON data')
        raw = admission.canonical(document)
        admission.require(len(raw) <= 131072, 'finite historical configuration required')
        _read_historical(raw, root)
        value = raw, root
        admission.require(_HISTORICAL is None or _HISTORICAL == value, 'historical configuration already pinned')
        _HISTORICAL = value
    except (admission.AdmissionError, admission.contract.ContractError, OSError, KeyError, TypeError, ValueError) as error:
        raise ControllerError('daycap historical inputs rejected: ' + str(error)) from error


def _historical_inputs():
    if _HISTORICAL is None:
        raise ControllerError('daycap historical inputs are not configured')
    try:
        return _read_historical(*_HISTORICAL)
    except (admission.AdmissionError, admission.contract.ContractError, OSError, KeyError, TypeError, ValueError) as error:
        raise ControllerError('daycap historical inputs changed: ' + str(error)) from error


def _is_daycap(request):
    return (request.get('action_id') == 'Q16b'
            and isinstance(request.get('action_inputs', {}).get('plan'), dict)
            and request['action_inputs']['plan'].get('schema_version') == daycap.VERSION)


def is_archived(request):
    return execution.is_archived(request)


def qualified_archive_profile(request, validation, *, deadline_ns):
    if not _is_daycap(request):
        return original_v28.qualified_archive_profile(request, validation, deadline_ns=deadline_ns)
    try:
        return overlay.qualified_profile(request, validation, deadline_ns=deadline_ns)
    except (ValueError, OSError, KeyError, TypeError) as error:
        raise ControllerError('daycap archive profile rejected: ' + str(error)) from error


def _validate_inputs(request, validation):
    if not _is_daycap(request):
        return original_v27._validate_inputs(request, validation)
    checked = {}

    def prior(result, prior, plan, selected_duration_ns):
        if prior != 'Q16a' or result.get('schema_version') != handoff.original.SCHEMA:
            raise ControllerError('daycap requires the actual retained Q16a handoff')
        config, context, old_validation, old_plan, proof = _historical_inputs()
        try:
            admission.same(proof['handoff'], request['action_inputs']['prerequisite_bindings']['q16a_validation'],
                           'actual signed handoff binding')
            checked['Q16a'] = handoff.consume(result, validation=validation, plan=plan,
                selected_duration_ns=selected_duration_ns, original_validation=old_validation,
                original_plan=old_plan, compatibility=config['compatibility'],
                original_boot_id=context['boot_id'], boot_id=config['boot_id'])
        except handoff.Error as error:
            raise ControllerError(str(error)) from error

    def ring(plan, ring_result, binding):
        return _v25.validate_ring_reuse(plan, checked.get('Q16a', ring_result), binding)

    # Original semantic body, including actual source/hardware/discovery counts
    # and the complete signed namespace. Only the contract/prior seam changes.
    return _v25._with_globals(_v25.validate_action_inputs,
        {'contract': contract, 'validate_prior_calibration': prior, 'validate_ring_reuse': ring,
         'registry': types.SimpleNamespace(**{**vars(registry), 'canonical': registry.archive.canonical})},
        dict(request=request, validation=validation))


def _prepare_archive(*, for_retention, **arguments):
    # Static v26 preparation body with its local registry import supplied by our
    # private daycap registry. The entire v25 authority body remains unchanged.
    profiles = []

    def validate(request, validation):
        if not is_archived(request):
            return _v25.validate_action_inputs(request, validation)
        extent = _validate_inputs(request, validation)
        profiles.append(qualified_archive_profile(request, validation,
            deadline_ns=time.monotonic_ns() + extent.declared.cleanup_ns))
        return extent

    prepared = _v25._with_globals(_v25._prepare_action,
        {'registry': registry, 'validate_action_inputs': validate},
        {'for_retention': for_retention, **arguments})
    if not is_archived(prepared.request):
        return prepared
    if len(profiles) != 1:
        raise ControllerError('archive implementation was not admitted exactly once')
    return PreparedArchiveAction(**{f.name: getattr(prepared, f.name) for f in fields(PreparedAction)},
                                 archive_runtime_profile=profiles[0])


