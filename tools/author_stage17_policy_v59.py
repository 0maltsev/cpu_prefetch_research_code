"""Render the minimal fresh policy59/preflight33 successor; no authority.

Start from immutable policy58 bytes, auditing all inherited bindings. Rebind
only the approved cold family C++ source and the two packaging selectors;
add the current generic runtime.
Never regenerate historical policies or silently refresh other old hashes.
"""
from __future__ import annotations

import argparse
import copy
import json
import pathlib
import sys

import author_stage17_policy_v58 as previous
import stage17_semantic_verifier_v59 as verifier
import stage17_read_only_preflight_semantic_verifier_v33 as preflight

_BASE = previous._BASE


def render_preflight(root):
    root = root.resolve()
    policy = json.loads((root / preflight.POLICY_V32_PATH).read_bytes())
    policy.update(schema_version='cpu-prefetch-stage17-read-only-preflight-evidence-admission-policy/33',
        policy_id='STAGE17-READ-ONLY-PREFLIGHT-EVIDENCE-ADMISSION-POLICY-v33', policy_version='33')
    policy['predecessor'].pop('policy_v31')
    policy['predecessor']['policy_v32'] = _BASE.binding(root, preflight.POLICY_V32_PATH)
    policy['implementations'] = {key: _BASE.binding(root, path)
                                 for key, path in preflight.IMPLEMENTATION_PATHS.items()}
    return policy


def render(root):
    root = root.resolve()
    historical = json.loads((root / verifier.predecessor.POLICY_PATH).read_bytes())
    policy = copy.deepcopy(historical)
    for key, value in policy['bindings'].items():
        if value['path'] in verifier.REBIND_PATHS:
            policy['bindings'][key] = _BASE.binding(root, value['path'])
    verifier.audit_inherited_bindings(root, policy, historical)
    roots = list(dict.fromkeys((*historical['runtime_import_roots'], *verifier.NEW_ROOTS)))
    policy.update(schema_version='cpu-prefetch-stage17-operational-evidence-admission-policy/59',
        policy_id='STAGE17-OPERATIONAL-EVIDENCE-ADMISSION-POLICY-v59', policy_version='59',
        predecessor=_BASE.binding(root, verifier.predecessor.POLICY_PATH.as_posix()),
        predecessor_status='SUPERSEDED_REBINDS_CURRENT_COLD_ARCHIVE', runtime_import_roots=roots,
        runtime_closure={pathlib.PurePosixPath(path).stem: _BASE.binding(root, path)
            for path in sorted(verifier.discover_python_closure(root, roots))},
        entries=[dict(input_id=key, status='IMPLEMENTED', verifier_id=verifier.VERIFIER_ID,
                      verifier_version=verifier.VERIFIER_VERSION) for key in verifier.INPUT_IDS])
    for path in sorted(set((*verifier.SUCCESSOR_BINDINGS, *verifier.FORMAL_DECISIONS))):
        key = path.replace('/', '__').replace('.', '_')
        policy['bindings'][key] = _BASE.binding(root, path)
    verifier.audit_inherited_bindings(root, policy, historical)
    verifier.verify_policy_v59(root=root, policy=policy, **{key: policy[key] for key in (
        'graph_sha256', 'catalog_sha256', 'genesis_record_sha256', 'resolution_schema_sha256')})
    return policy


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--root', type=pathlib.Path, default=pathlib.Path(__file__).resolve().parents[1])
    parser.add_argument('--preflight', action='store_true')
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    path = preflight.POLICY_PATH if args.preflight else verifier.POLICY_PATH
    payload = _BASE.canonical((render_preflight if args.preflight else render)(args.root))
    if args.check:
        if not (args.root / path).is_file() or (args.root / path).read_bytes() != payload:
            print('stage17-policy-v59: FAIL generated bytes differ: ' + str(path), file=sys.stderr)
            return 1
        print('stage17-policy-v59: PASS ' + str(path))
        return 0
    sys.stdout.buffer.write(payload)
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
