"""Read-only original-source verification for the frozen D310 S180 plan.

Uses the unchanged accepted Philox/Decimal80 primitives. This checks generation
and common-source membership, not namespace freshness, qualification, resources
or execution authority. The qualified parent must authenticate those separately.
"""
from __future__ import annotations

import decimal
import hashlib
import os
from pathlib import Path
import stat
import struct
import time
from fractions import Fraction
from jsonschema.exceptions import ValidationError

import generate_schedule as generator
import stage17_formal_archive_v1 as archive
import stage17_q16c_schedule_provenance_v1 as metadata
import stage17_s180_plan_prepare_v1 as planning

SCHEMA = "cpu-prefetch-stage17-s180-source-provenance/1"
RECORD_FIELDS = frozenset(("placement", "working_set_class", "load_level", "phase",
                           "binary", "envelope", "derivation"))
FILE_FIELDS = frozenset(("artifact_id", "path", "size_bytes", "sha256"))


class SourceError(archive.ArchiveError):
    pass


def require(condition, message):
    if not condition:
        raise SourceError("S180 source provenance: " + message)


def _check_deadline(deadline_ns):
    require(type(deadline_ns) is int and time.monotonic_ns() < deadline_ns,
            "source-verification deadline expired")


def _fields(value, fields, label):
    require(type(value) is dict and set(value) == fields, label + " fields differ")


def _stamp(st):
    return (st.st_dev, st.st_ino, st.st_mode, st.st_uid, st.st_size, st.st_mtime_ns, st.st_ctime_ns)


def _integer_control(value):
    pending, nodes = [(value,0)], 0
    while pending:
        item, depth = pending.pop(); nodes += 1
        require(nodes <= 1_000_000 and depth <= 64, "source control structure bound")
        require(type(item) is not float, "floating-point source control is forbidden")
        if type(item) is dict:
            pending.extend((v,depth+1) for pair in item.items() for v in pair)
        elif type(item) is list:
            pending.extend((v,depth+1) for v in item)


def expected_sources(plan, *, seed_id):
    """Derive all36 expectations from the exact plan; no generated bytes or I/O."""
    require(type(seed_id) is str and 0 < len(seed_id) <= 512
            and all(ord(c) >= 32 and ord(c) != 127 for c in seed_id), "prospective seed identity required")
    require(plan.get("schema_version") == planning.PLAN and "source_count_basis" not in plan,
            "concrete S180 collection-plan candidate required")
    # Reuse the exact frozen grouping checks, without changing the supplied
    # plan or representing a sizing document as an admitted collection plan.
    groups, order = planning.source_groups(dict(plan, schema_version=planning.SIZING))
    blueprint = plan["blueprint"]
    rows = {(r["placement"], r["working_set_class"], r["load_level"]):r
            for r in blueprint["captures"]}
    out = []
    for key in order:
        row = rows[key]
        for phase_index, phase in enumerate(("warmup", "measurement")):
            source = groups[key][phase_index]
            require(source["source_artifact"] is not None, "original source binding required")
            nominal = row["nominal_rate"]
            rate = Fraction(nominal["numerator"], nominal["denominator"] * 10**12)
            out.append(dict(placement=key[0], working_set_class=key[1], load_level=key[2], phase=phase,
                schedule_id=source["schedule_id"], namespace_id=row[phase + "_schedule_namespace"],
                parent_namespace_id=blueprint["blueprint_id"] + "/PILOT", seed_id=seed_id,
                master_seed_hex=blueprint["master_seed_hex"], origin_ticks=source["source_origin_ticks"],
                horizon_ticks=source["source_horizon_ticks"]-source["source_origin_ticks"],
                offered_count=source["offered_count"], source_artifact=source["source_artifact"],
                schedule_kind="WARMUP" if phase_index == 0 else "PILOT",
                nominal_offered_rate=dict(numerator_events=rate.numerator, denominator_ticks=rate.denominator)))
    return out


class _Files:
    def __init__(self, deadline_ns):
        self.deadline = deadline_ns
        self.observed = {}
        self.inodes = set()

    def open(self, binding):
        _check_deadline(self.deadline)
        _fields(binding, FILE_FIELDS, "source artifact")
        require(type(binding["artifact_id"]) is str and 0 < len(binding["artifact_id"]) <= 512,
                "bounded artifact identity required")
        archive.uint(binding["size_bytes"], "source size")
        archive.sha(binding["sha256"], "source hash")
        require(type(binding["path"]) is str, "source path must be text")
        path = Path(binding["path"])
        require(path.is_absolute() and str(path) == binding["path"]
                and path.resolve(strict=True) == path, "absolute nonsymlink source path required")
        require(path not in self.observed, "source path reused")
        fd = os.open(path, os.O_RDONLY | os.O_CLOEXEC | os.O_NOFOLLOW | os.O_NONBLOCK)
        try:
            st = os.fstat(fd)
            require(stat.S_ISREG(st.st_mode) and not st.st_mode & 0o022
                    and st.st_size == binding["size_bytes"], "unsafe or wrong-sized original source")
            require((st.st_dev, st.st_ino) not in self.inodes, "source inode reused")
            self.inodes.add((st.st_dev, st.st_ino))
            self.observed[path] = _stamp(st)
            return os.fdopen(fd, "rb")
        except BaseException:
            os.close(fd)
            raise

    def document(self, binding, schema):
        require(0 < binding["size_bytes"] <= metadata.MAX_METADATA_BYTES, "source metadata byte bound")
        with self.open(binding) as stream:
            raw = stream.read(metadata.MAX_METADATA_BYTES+1)
        reduced = {k:binding[k] for k in ("artifact_id", "size_bytes", "sha256")}
        return metadata._metadata(raw, reduced, schema)

    def finish(self):
        _check_deadline(self.deadline)
        for path, before in self.observed.items():
            require(path.resolve(strict=True) == path and _stamp(path.lstat()) == before,
                    "original source changed during bank verification")


def _verify_one(expected, record, files):
    binary = record["binary"]
    require({k:binary[k] for k in ("artifact_id", "sha256")} == expected["source_artifact"],
            "native/original binary binding differs")
    count = expected["offered_count"]
    require(binary["size_bytes"] == archive.checked_product(count, 8), "original count/byte extent differs")
    envelope = files.document(record["envelope"], "protocol/2.0.0-pre.3/handoff/schemas/schedule.schema.json")
    derivation = files.document(record["derivation"], "config/schemas/schedule-derivation-v2.schema.json")
    metadata._self_hash(envelope, "schedule_sha256")
    metadata._self_hash(derivation, "record_sha256")
    fields = ("schedule_id", "namespace_id", "schedule_kind", "origin_ticks", "horizon_ticks",
              "offered_count", "nominal_offered_rate")
    require(archive.canonical({k:envelope[k] for k in fields}) ==
            archive.canonical({k:expected[k] for k in fields}), "frozen phase/namespace/coordinates/rate differ")
    require(envelope["arrival_family"] == "POISSON_EXPONENTIAL" and envelope["time_unit"] == "ps"
            and envelope["deadline_encoding"] == "ABSOLUTE_INTEGER_TICKS"
            and envelope["overflow_rule_record_id"] == generator.OVERFLOW_RULE
            and envelope["inclusion_boundary"] == dict(start_inclusive=True, end_exclusive=True)
            and envelope["immutable_ordering"] is True, "accepted schedule semantics differ")
    rng = dict(algorithm=generator.SCHEDULE_ALGORITHM, version=generator.SCHEDULE_VERSION,
        seed_id=expected["seed_id"], derivation_record_id=derivation["record_id"],
        parent_namespace_id=expected["parent_namespace_id"])
    require(envelope["rng"] == rng and all(derivation[k] == expected[k] for k in
        ("seed_id", "namespace_id", "parent_namespace_id")), "prospective seed/derivation ancestry differs")
    storage = envelope["deadline_storage"]
    require(storage["mode"] == "EXTERNAL_IMMUTABLE_ARTIFACT"
            and all(storage[k] == v for k,v in dict(artifact_id=binary["artifact_id"],
                artifact_sha256=binary["sha256"], byte_count=binary["size_bytes"], row_count=count).items()),
            "original binary envelope binding differs")
    rate = expected["nominal_offered_rate"]
    spec = generator.ScheduleSpec(expected["schedule_id"], expected["schedule_kind"], expected["namespace_id"],
        expected["parent_namespace_id"], expected["seed_id"], derivation["record_id"],
        bytes.fromhex(expected["master_seed_hex"]), expected["origin_ticks"], expected["horizon_ticks"],
        rate["numerator_events"], rate["denominator_ticks"], binary["artifact_id"], storage["artifact_uri"])
    generator._require_python_runtime()
    generator.validate_spec(spec)
    key = generator._derive_key(spec.master_seed, spec.namespace_id)
    require(derivation["derived_key_u32be_hex"] == f"{key[0]:08x}{key[1]:08x}", "derived key differs")
    decoded = hashlib.sha256()
    for value in (b"cpu-prefetch/decoded-deadlines-sha256/v1", generator.DERIVATION_DOMAIN_PROTOCOL_VERSION.encode(),
                  generator.SCHEDULE_SUITE.encode(), b"ps", *(struct.pack(">Q", n) for n in
                  (spec.origin_ticks, spec.horizon_ticks, spec.numerator_events, spec.denominator_ticks, count))):
        metadata._append(decoded, value)
    digest, total = hashlib.sha256(), decimal.Decimal(0)
    end = archive.checked_sum(spec.origin_ticks, spec.horizon_ticks)
    with files.open(binary) as stream, decimal.localcontext(generator._decimal_context(decimal)) as active:
        for ordinal in range(count+1):
            if ordinal % 256 == 0:
                _check_deadline(files.deadline)
            next_total = generator._advance_cumulative(active, decimal, total,
                generator._philox_draw(key, ordinal), spec.numerator_events, spec.denominator_ticks)
            require(next_total.is_finite() and next_total > total, "accepted generator made no progress")
            total = next_total
            offset = int(total.to_integral_value(rounding=decimal.ROUND_FLOOR, context=active))
            deadline = archive.checked_sum(spec.origin_ticks, offset)
            if ordinal == count:
                require(deadline >= end, "source omits generated in-window arrivals")
                break
            raw = stream.read(8)
            require(len(raw) == 8 and struct.unpack(">Q", raw)[0] == deadline < end,
                    "original/accepted-generated deadline differs")
            digest.update(raw)
            metadata._append(decoded, raw)
        require(stream.read(1) == b"", "original source has trailing bytes")
    require(digest.hexdigest() == binary["sha256"] and decoded.hexdigest() == envelope["decoded_deadlines_sha256"],
            "original/decoded source hash differs")
    return dict(expected, binary=record["binary"], envelope=record["envelope"], derivation=record["derivation"],
                schedule_sha256=envelope["schedule_sha256"], derivation_record_id=derivation["record_id"],
                derivation_record_sha256=derivation["record_sha256"],
                decoded_deadlines_sha256=decoded.hexdigest(), accepted_generation_verified=True)


def _verify_bank(*, plan, seed_id, records, maximum_source_bytes, deadline_ns):
    """Verify all36 original binaries/envelopes/derivations, streaming regeneration.

    No writes, publication, retry, authority or freshness assertions. The caller
    supplies its prospectively authenticated seed ID and finite time/byte budget.
    """
    _check_deadline(deadline_ns)
    require(type(records) is list and len(records) == 36, "exactly36 original source records required")
    _integer_control(plan)
    _integer_control(records)
    plan_raw, record_raw = archive.canonical(plan), archive.canonical(records)
    require(len(plan_raw) <= 16*1024**2 and len(record_raw) <= 1024**2, "source control-byte bound")
    plan = archive.parse_json(plan_raw)
    # Copy control values before I/O so the proof cannot alias caller bindings.
    records = archive.parse_json(archive.canonical(dict(records=records)))["records"]
    expected = expected_sources(plan, seed_id=seed_id)
    maximum = archive.uint(maximum_source_bytes, "source byte limit", positive=True)
    size = archive.checked_sum(*(archive.checked_product(e["offered_count"],8) for e in expected))
    require(size <= maximum, "declared source bank exceeds its byte budget")
    index, artifacts = {}, set()
    for record in records:
        _fields(record, RECORD_FIELDS, "source record")
        key = tuple(record[k] for k in ("placement", "working_set_class", "load_level", "phase"))
        require(key not in index, "duplicate source coordinates")
        index[key] = record
        for name in ("binary", "envelope", "derivation"):
            _fields(record[name], FILE_FIELDS, name)
            identity = record[name]["artifact_id"]
            require(type(identity) is str and identity not in artifacts, "duplicate source artifact identity")
            artifacts.add(identity)
    keys = [tuple(e[k] for k in ("placement", "working_set_class", "load_level", "phase")) for e in expected]
    require(set(index) == set(keys), "source bank omits or substitutes frozen coordinates")
    files = _Files(deadline_ns)
    reports = [_verify_one(e,index[key],files) for e,key in zip(expected,keys,strict=True)]
    files.finish()
    require(len({r["derivation_record_id"] for r in reports}) == 36, "derivation record identity reused")
    return dict(schema_version=SCHEMA, plan_sha256=planning.sha(plan), source_count=36,
        original_source_bytes=size, sources=reports, accepted_generation_verified=True,
        namespace_freshness_verified=False, resource_admission_performed=False,
        execution_authority=False, phase18_authority=False)


def verify_source_bank(*, plan, seed_id, records, maximum_source_bytes, deadline_ns):
    """Generation/membership proof only; malformed or changed inputs fail closed."""
    try:
        return _verify_bank(plan=plan, seed_id=seed_id, records=records,
            maximum_source_bytes=maximum_source_bytes, deadline_ns=deadline_ns)
    except SourceError:
        raise
    except (archive.ArchiveError, ValueError, TypeError, KeyError, OSError, ArithmeticError, ValidationError) as error:
        raise SourceError("S180 source provenance: " + str(error)) from error
